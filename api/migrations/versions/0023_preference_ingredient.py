# 衛福部's eleven food-label allergen groups, as they appear on Taiwanese packaging. Copied here
# because a CHECK cannot import, exactly as 0022 copied D38's ten. **The list is closed and refused
# rather than coerced** — a value outside it is rejected, because coercing 「腰果」 to 堅果類 would
# turn a wrong answer into a plausible one, and here a plausible-but-wrong answer is one somebody
# eats.
INGREDIENTS = (
    "甲殼類", "芒果", "花生", "牛奶／羊奶", "蛋", "堅果類",
    "芝麻", "含麩質之穀物", "大豆", "魚類", "亞硫酸鹽類",
)

CATEGORIES = ("麵食", "飯食", "小吃", "火鍋", "燒烤", "日式", "西式", "早餐", "咖啡飲料", "其他")
BUDGET_BANDS = ("tight", "easy")
KINDS = ("budget", "avoid_category", "avoid_ingredient")
AVOIDANCES = ("avoid_category", "avoid_ingredient")


def _in(column: str, values) -> str:
    return "{} in ({})".format(column, ", ".join("'{}'".format(v) for v in values))


def upgrade() -> None:
    # The kind list widens. Dropped and recreated rather than added to, because a CHECK is a whole
    # expression and there is no ALTER for part of one.
    op.drop_constraint("ck_preference_kind", "preference", type_="check")
    op.create_check_constraint("ck_preference_kind", "preference", _in("kind", KINDS))

    op.create_check_constraint(
        "ck_preference_ingredient_value", "preference",
        "(kind <> 'avoid_ingredient') or ({})".format(_in("value", INGREDIENTS)),
    )

    # **The stance biconditional now covers both avoidances, and the constraint is renamed.** It was
