    # be a comment that lies in the one place nobody edits — a constraint name shows up in the error
    # a client sees.
    op.drop_constraint("ck_preference_stance_only_on_category", "preference", type_="check")
    op.create_check_constraint(
        "ck_preference_stance_only_on_avoidance", "preference",
        "({}) = (stance is not null)".format(_in("kind", AVOIDANCES)),
    )

    # `ck_preference_budget_expires` is untouched: a budget still always expires and **an ingredient
    # avoidance still never does.** B1's re-confirmation for this kind is a screen behaviour, not a
    # lapse — see the header. Writing `expires_on` here would make the row disappear from "in force"
    # and silently switch an avoidance off, which is the opposite of asking again.

    # Uniqueness per value, the same shape as the category's and a separate partial index rather
    # than a widened one. Two kinds in one index would collide the day a value appeared in both
    # closed lists — none does today, and a schema that only works while two lists stay disjoint is
    # a schema waiting for a list to change.
    op.create_index(
        "uq_preference_ingredient_version", "preference", ["member_id", "value", "valid_from"],
        unique=True, postgresql_where=sa.text("kind = 'avoid_ingredient'"),
    )


