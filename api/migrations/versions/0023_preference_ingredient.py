"""A1 / D103 — a third kind of preference: 「不吃 X」, recorded as a choice and never as a condition.

Revision ID: 0023
Revises: 0022
Created: 2026-08-18

Hand-written, not autogenerated (H10). Owner-ruled 2026-08-18 (D103 amended).

**This is the product's founding reason, and the reason it is shaped this way is the PDPA.** A
person who cannot eat peanuts has to be able to say so, and the app has to act on it. What it must
**not** do is record *why*. 「不吃花生」 is a preference; 「花生過敏」 is health information about an
identified person, and holding that would put a dinner app inside a regime built for medical
records. So the table stores an avoidance, the value list happens to be 衛福部's food-label
allergen groups because that is the list Taiwanese packaging already uses, and **no surface may
contain the word 過敏** — that rule belongs to the copy and is stated in D103 rather than here,
because a CHECK cannot enforce it and pretending otherwise would be worse than writing it down.

**Nothing about the mechanism is new, which is the point of adding it as a third `kind` rather than
a fourth table.** `stance` works exactly as it does for a category, so un-avoiding appends `allow`
and a mis-tap is reversible; uniqueness is per `(member_id, value)` for the same reason it is for a
category — a person may avoid 花生 and 甲殼類 both, so one row in force *per value* is the rule and
one row in force per kind would allow exactly one avoidance. **Rejected: a separate
`preference_ingredient` table** — it would duplicate `stance`, `persist`, the versioning and the
`weight_contribution` key for a row that differs only in which closed list its value comes from.

**Two things that differ from `avoid_category`, and both are deliberate.**

**It does not expire, and it is not inherited either.** D25's rule for a category stance is that it
stands until changed. B1's carry rule for *this* kind is narrower: **show, and require the tap even
for a stance.** A category stance is a taste, and a taste held last month is still yours this
month. An ingredient stance is a fact about a body, and the honest thing is to re-offer it and let
the person confirm rather than assume it silently. So `expires_on` stays NULL by CHECK — the row
does not lapse — and the *screen* asks again. Anyone tempted to make the two kinds' date handling
consistent should read this paragraph first: the inconsistency is the ruling.

**It is never applied by speak-for.** One person may roll on behalf of a circle, and they may not
carry someone else's ingredient avoidance into a round the absent person did not join. That is an
API rule rather than a schema one and lives in the loader; recorded here because the table is where
someone will come looking for it.

**The contributor does nothing today and that is stated rather than hidden.** No place carries
ingredient data — there is no source for it and none planned — so an ingredient avoidance is stored
and produces no contribution. `GET /circles/{id}/preferences` reports `ingredient_coverage`, which
is 0 today, for the same reason it reports `category_coverage`: a screen offering eleven choices
that change nothing must be able to say so, and the figure must never be written into markup.
"""

